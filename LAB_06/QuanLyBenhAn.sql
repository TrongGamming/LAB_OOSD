-- Chay bang schema BENHAN. Chay lai se xoa du lieu cu cua rieng schema nay.
SET DEFINE OFF
SET SERVEROUTPUT ON
BEGIN
  FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN
    ('PHANUNGTHUOC','CHITIETTOA','TOATHUOC','KETQUAXETNGHIEM','CHIDINHXETNGHIEM',
     'TRIEUCHUNG','LUOTKHAM','LICHHEN','PHITHU','HOSOBENHAN','PHIEUDANGKY',
     'BENHNHAN','BACSI','KHOA','THUOC','LOAIXETNGHIEM')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE '||t.table_name||' CASCADE CONSTRAINTS PURGE';
  END LOOP;
  FOR s IN (SELECT sequence_name FROM user_sequences WHERE sequence_name IN
    ('SEQ_BN','SEQ_DK','SEQ_HS','SEQ_THU','SEQ_HEN','SEQ_KHAM','SEQ_TRIEU','SEQ_CD','SEQ_KQ','SEQ_TOA','SEQ_CT','SEQ_PU')) LOOP
    EXECUTE IMMEDIATE 'DROP SEQUENCE '||s.sequence_name;
  END LOOP;
END;
/

CREATE TABLE BenhNhan (
  MaBN VARCHAR2(12) PRIMARY KEY, HoTen NVARCHAR2(100) NOT NULL,
  DiaChi NVARCHAR2(250) NOT NULL, NgaySinh DATE NOT NULL,
  DienThoai VARCHAR2(15) NOT NULL, Anh3x4 VARCHAR2(500),
  CONSTRAINT CK_BN_DT CHECK (REGEXP_LIKE(DienThoai,'^[0-9]{9,15}$'))
);
CREATE TABLE PhieuDangKy (
  MaDK VARCHAR2(12) PRIMARY KEY, MaBN VARCHAR2(12) NOT NULL REFERENCES BenhNhan(MaBN),
  NgayDangKy DATE DEFAULT SYSDATE NOT NULL, NamApDung NUMBER(4) NOT NULL,
  TrangThai VARCHAR2(15) DEFAULT 'CHO_THU' NOT NULL,
  CONSTRAINT UQ_DK_BN_NAM UNIQUE(MaBN,NamApDung),
  CONSTRAINT CK_DK_TT CHECK (TrangThai IN ('CHO_THU','DA_THU'))
);
CREATE TABLE PhiThu (
  MaThu VARCHAR2(12) PRIMARY KEY, MaDK VARCHAR2(12) NOT NULL UNIQUE REFERENCES PhieuDangKy(MaDK),
  SoTien NUMBER(12,0) NOT NULL CHECK (SoTien>0), NgayThu DATE DEFAULT SYSDATE NOT NULL,
  LoaiPhi VARCHAR2(15) DEFAULT 'HANG_NAM' NOT NULL CHECK (LoaiPhi='HANG_NAM')
);
CREATE TABLE HoSoBenhAn (
  MaHS VARCHAR2(12) PRIMARY KEY, MaBN VARCHAR2(12) NOT NULL UNIQUE REFERENCES BenhNhan(MaBN),
  NgayCap DATE DEFAULT SYSDATE NOT NULL, TrangThai VARCHAR2(15) DEFAULT 'HOAT_DONG' NOT NULL,
  CONSTRAINT CK_HS_TT CHECK(TrangThai IN ('HOAT_DONG','NGUNG'))
);
CREATE TABLE Khoa (
  MaKhoa VARCHAR2(10) PRIMARY KEY, TenKhoa NVARCHAR2(100) NOT NULL UNIQUE
);
CREATE TABLE BacSi (
  MaBS VARCHAR2(10) PRIMARY KEY, HoTen NVARCHAR2(100) NOT NULL,
  MaKhoa VARCHAR2(10) NOT NULL REFERENCES Khoa(MaKhoa)
);
CREATE TABLE LichHen (
  MaHen VARCHAR2(12) PRIMARY KEY, MaHS VARCHAR2(12) NOT NULL REFERENCES HoSoBenhAn(MaHS),
  MaBS VARCHAR2(10) REFERENCES BacSi(MaBS), ThoiGian DATE NOT NULL,
  LoaiKham VARCHAR2(15) NOT NULL CHECK(LoaiKham IN ('DIEU_TRI','DINH_KY')),
  TrangThai VARCHAR2(15) DEFAULT 'DA_HEN' NOT NULL CHECK(TrangThai IN ('DA_HEN','DA_DEN','HUY')),
  CONSTRAINT UQ_HEN_BS_GIO UNIQUE(MaBS,ThoiGian)
);
CREATE TABLE LuotKham (
  MaKham VARCHAR2(12) PRIMARY KEY, MaHS VARCHAR2(12) NOT NULL REFERENCES HoSoBenhAn(MaHS),
  MaHen VARCHAR2(12) UNIQUE REFERENCES LichHen(MaHen), MaBS VARCHAR2(10) NOT NULL REFERENCES BacSi(MaBS),
  MaKhoa VARCHAR2(10) NOT NULL REFERENCES Khoa(MaKhoa), NgayGio DATE DEFAULT SYSDATE NOT NULL,
  LoaiKham VARCHAR2(15) NOT NULL CHECK(LoaiKham IN ('DIEU_TRI','DINH_KY')),
  ChanDoan NVARCHAR2(500), KetLuan NVARCHAR2(1000),
  TrangThai VARCHAR2(20) DEFAULT 'DANG_KHAM' NOT NULL CHECK(TrangThai IN ('DANG_KHAM','CHO_XET_NGHIEM','CHO_TOA','CHO_THANH_TOAN','HOAN_TAT')),
  NgayXuatVien DATE, VienPhi NUMBER(12,0) DEFAULT 0 NOT NULL CHECK(VienPhi>=0),
  DaThanhToan CHAR(1) DEFAULT 'N' NOT NULL CHECK(DaThanhToan IN ('Y','N')),
  CONSTRAINT CK_KHAM_HOANTAT CHECK(TrangThai<>'HOAN_TAT' OR (NgayXuatVien IS NOT NULL AND DaThanhToan='Y'))
);
CREATE TABLE TrieuChung (
  MaTrieuChung VARCHAR2(12) PRIMARY KEY, MaKham VARCHAR2(12) NOT NULL REFERENCES LuotKham(MaKham),
  MoTa NVARCHAR2(300) NOT NULL, ThanNhiet NUMBER(4,1), HuyetAp VARCHAR2(20)
);
CREATE TABLE LoaiXetNghiem (
  MaXN VARCHAR2(10) PRIMARY KEY, TenXN NVARCHAR2(100) NOT NULL UNIQUE
);
CREATE TABLE ChiDinhXetNghiem (
  MaCD VARCHAR2(12) PRIMARY KEY, MaKham VARCHAR2(12) NOT NULL REFERENCES LuotKham(MaKham),
  MaXN VARCHAR2(10) NOT NULL REFERENCES LoaiXetNghiem(MaXN), MaBS VARCHAR2(10) NOT NULL REFERENCES BacSi(MaBS),
  NgayChiDinh DATE DEFAULT SYSDATE NOT NULL, TrangThai VARCHAR2(15) DEFAULT 'CHO_KQ' NOT NULL CHECK(TrangThai IN ('CHO_KQ','DA_CO_KQ'))
);
CREATE TABLE KetQuaXetNghiem (
  MaKQ VARCHAR2(12) PRIMARY KEY, MaCD VARCHAR2(12) NOT NULL UNIQUE REFERENCES ChiDinhXetNghiem(MaCD),
  KetQua NVARCHAR2(1000) NOT NULL, NgayCoKQ DATE DEFAULT SYSDATE NOT NULL
);
CREATE TABLE Thuoc (
  MaThuoc VARCHAR2(10) PRIMARY KEY, TenThuoc NVARCHAR2(100) NOT NULL,
  DonVi NVARCHAR2(30) NOT NULL, HuongDan NVARCHAR2(250)
);
CREATE TABLE ToaThuoc (
  MaToa VARCHAR2(12) PRIMARY KEY, MaKham VARCHAR2(12) NOT NULL UNIQUE REFERENCES LuotKham(MaKham),
  MaBS VARCHAR2(10) NOT NULL REFERENCES BacSi(MaBS), NgayKe DATE DEFAULT SYSDATE NOT NULL,
  LoiDan NVARCHAR2(500), TrangThai VARCHAR2(15) DEFAULT 'NHAP' NOT NULL CHECK(TrangThai IN ('NHAP','DA_KY'))
);
CREATE TABLE ChiTietToa (
  MaCT VARCHAR2(12) PRIMARY KEY, MaToa VARCHAR2(12) NOT NULL REFERENCES ToaThuoc(MaToa),
  MaThuoc VARCHAR2(10) NOT NULL REFERENCES Thuoc(MaThuoc), SoLuong NUMBER(6) NOT NULL CHECK(SoLuong>0),
  LieuDung NVARCHAR2(150) NOT NULL, SoNgay NUMBER(3) NOT NULL CHECK(SoNgay>0),
  CONSTRAINT UQ_CT_THUOC UNIQUE(MaToa,MaThuoc)
);
CREATE TABLE PhanUngThuoc (
  MaPU VARCHAR2(12) PRIMARY KEY, MaHS VARCHAR2(12) NOT NULL REFERENCES HoSoBenhAn(MaHS),
  MaThuoc VARCHAR2(10) NOT NULL REFERENCES Thuoc(MaThuoc), NgayGhiNhan DATE DEFAULT SYSDATE NOT NULL,
  MoTa NVARCHAR2(500) NOT NULL, MucDo VARCHAR2(15) NOT NULL CHECK(MucDo IN ('NHE','VUA','NANG'))
);

