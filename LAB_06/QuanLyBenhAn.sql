CREATE OR REPLACE TRIGGER TRG_THU_DANGKY AFTER INSERT ON PhiThu FOR EACH ROW
BEGIN
  UPDATE PhieuDangKy SET TrangThai='DA_THU' WHERE MaDK=:NEW.MaDK;
END;
