SET DEFINE OFF
SET SQLBLANKLINES ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE TABLE PhongBan (
 MaPB VARCHAR2(12) PRIMARY KEY, TenPB NVARCHAR2(100) NOT NULL UNIQUE
);
CREATE TABLE ChucVu (
 MaCV VARCHAR2(12) PRIMARY KEY, TenCV NVARCHAR2(100) NOT NULL UNIQUE
);
CREATE TABLE NhanVien (
 MaNV VARCHAR2(12) PRIMARY KEY, HoTen NVARCHAR2(100) NOT NULL,
 NgaySinh DATE NOT NULL, CCCD VARCHAR2(12) NOT NULL UNIQUE,
 DienThoai VARCHAR2(15), DiaChi NVARCHAR2(200),
 MaPB VARCHAR2(12) NOT NULL REFERENCES PhongBan(MaPB),
 TrangThai VARCHAR2(20) DEFAULT 'THU_VIEC' NOT NULL
 CHECK (TrangThai IN ('THU_VIEC','CHINH_THUC','NGHI_VIEC')),
 CHECK(REGEXP_LIKE(CCCD,'^[0-9]{12}$'))
);
CREATE TABLE QDTuyenDung (
 MaQD VARCHAR2(12) PRIMARY KEY, MaNV VARCHAR2(12) NOT NULL UNIQUE REFERENCES NhanVien(MaNV),
 MaPB VARCHAR2(12) NOT NULL REFERENCES PhongBan(MaPB), NgayKy DATE NOT NULL,
 TuNgay DATE NOT NULL, DenNgay DATE NOT NULL, LuongThuViec NUMBER(15,2) NOT NULL CHECK(LuongThuViec>0),
 DieuKhoan NVARCHAR2(1000) NOT NULL, NguoiKy NVARCHAR2(100) NOT NULL,
 KetQua VARCHAR2(12) DEFAULT 'CHO' NOT NULL CHECK(KetQua IN ('CHO','DAT','KHONG_DAT')),
 CHECK(TuNgay<=DenNgay AND NgayKy<=TuNgay)
);
CREATE TABLE HopDong (
 MaHD VARCHAR2(12) PRIMARY KEY, MaNV VARCHAR2(12) NOT NULL REFERENCES NhanVien(MaNV),
 LoaiHD VARCHAR2(12) NOT NULL CHECK(LoaiHD IN ('DAI_HAN','NGAN_HAN')),
 NgayKy DATE NOT NULL, TuNgay DATE NOT NULL, DenNgay DATE,
 DieuKhoan NVARCHAR2(1000) NOT NULL, NguoiKy NVARCHAR2(100) NOT NULL,
 CHECK(TuNgay>=NgayKy AND (DenNgay IS NULL OR DenNgay>=TuNgay)),
 CHECK(LoaiHD<>'NGAN_HAN' OR DenNgay IS NOT NULL)
);
CREATE TABLE HoSoBaoHiem (
 MaBH VARCHAR2(12) PRIMARY KEY, MaHD VARCHAR2(12) NOT NULL UNIQUE REFERENCES HopDong(MaHD),
 SoBHXH VARCHAR2(30) NOT NULL UNIQUE, SoBHYT VARCHAR2(30) NOT NULL UNIQUE,
 TyLeXH NUMBER(6,5) NOT NULL, TyLeYT NUMBER(6,5) NOT NULL,
 CHECK(TyLeXH>=0 AND TyLeYT>=0 AND TyLeXH+TyLeYT<1)
);
CREATE TABLE QDLuong (
 MaQD VARCHAR2(12) PRIMARY KEY, MaNV VARCHAR2(12) NOT NULL REFERENCES NhanVien(MaNV),
 NgayKy DATE NOT NULL, HieuLuc DATE NOT NULL, LuongCB NUMBER(15,2) NOT NULL CHECK(LuongCB>0),
 PCLuong NUMBER(15,2) DEFAULT 0 NOT NULL CHECK(PCLuong>=0),
 PCDocHai NUMBER(15,2) DEFAULT 0 NOT NULL CHECK(PCDocHai>=0),
 NguoiKy NVARCHAR2(100) NOT NULL, UNIQUE(MaNV,HieuLuc),
 CHECK(NgayKy<=HieuLuc AND HieuLuc=TRUNC(HieuLuc,'MM'))
);
CREATE TABLE QDChucVu (
 MaQD VARCHAR2(12) PRIMARY KEY, MaNV VARCHAR2(12) NOT NULL REFERENCES NhanVien(MaNV),
 MaCV VARCHAR2(12) NOT NULL REFERENCES ChucVu(MaCV), NgayKy DATE NOT NULL, HieuLuc DATE NOT NULL,
 PhuCap NUMBER(15,2) DEFAULT 0 NOT NULL CHECK(PhuCap>=0), NguoiKy NVARCHAR2(100) NOT NULL,
 UNIQUE(MaNV,HieuLuc), CHECK(NgayKy<=HieuLuc AND HieuLuc=TRUNC(HieuLuc,'MM'))
);
CREATE TABLE CaLam (
 MaCa VARCHAR2(12) PRIMARY KEY, TenCa NVARCHAR2(50) NOT NULL,
 GioBatDau NUMBER(2) NOT NULL CHECK(GioBatDau BETWEEN 0 AND 23),
 SoGio NUMBER(4,2) NOT NULL CHECK(SoGio>0 AND SoGio<=8)
);
CREATE TABLE KeHoachTuan (
 MaKH VARCHAR2(12) PRIMARY KEY, MaPB VARCHAR2(12) NOT NULL REFERENCES PhongBan(MaPB),
 DauTuan DATE NOT NULL, NguoiLap NVARCHAR2(100) NOT NULL,
 UNIQUE(MaPB,DauTuan), CHECK(DauTuan=TRUNC(DauTuan,'IW'))
);
CREATE TABLE PhanCong (
 MaPC VARCHAR2(12) PRIMARY KEY, MaKH VARCHAR2(12) NOT NULL REFERENCES KeHoachTuan(MaKH),
 MaNV VARCHAR2(12) NOT NULL REFERENCES NhanVien(MaNV), NgayLam DATE NOT NULL,
 MaCa VARCHAR2(12) NOT NULL REFERENCES CaLam(MaCa), GioPTDuKien NUMBER(4,2) DEFAULT 0 NOT NULL CHECK(GioPTDuKien BETWEEN 0 AND 16),
 UNIQUE(MaNV,NgayLam), CHECK(NgayLam=TRUNC(NgayLam))
);
CREATE TABLE ChamCong (
 MaCC VARCHAR2(12) PRIMARY KEY, MaPC VARCHAR2(12) NOT NULL UNIQUE REFERENCES PhanCong(MaPC),
 GioLam NUMBER(4,2) NOT NULL CHECK(GioLam BETWEEN 0 AND 8),
 NguoiCham NVARCHAR2(100) NOT NULL, GhiChu NVARCHAR2(200)
);
CREATE TABLE PhieuPhuTroi (
 MaPT VARCHAR2(12) PRIMARY KEY, NgayPT DATE NOT NULL,
 HinhThuc VARCHAR2(12) NOT NULL CHECK(HinhThuc IN ('TANG_CA','NGAY_LE','NGAY_NGHI')),
 NguoiLap NVARCHAR2(100) NOT NULL, CHECK(NgayPT=TRUNC(NgayPT))
);
CREATE TABLE CTPhuTroi (
 MaPT VARCHAR2(12) NOT NULL REFERENCES PhieuPhuTroi(MaPT),
 MaNV VARCHAR2(12) NOT NULL REFERENCES NhanVien(MaNV), SoGio NUMBER(4,2) NOT NULL CHECK(SoGio>0 AND SoGio<=16),
 PRIMARY KEY(MaPT,MaNV)
);
CREATE TABLE QuyetDinhKTKL (
 MaQD VARCHAR2(12) PRIMARY KEY, LoaiQD VARCHAR2(12) NOT NULL CHECK(LoaiQD IN ('KHEN_THUONG','KY_LUAT')),
 LyDo NVARCHAR2(500) NOT NULL, NgayLap DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
 CachXuLy VARCHAR2(12) NOT NULL CHECK(CachXuLy IN ('TRUC_TIEP','QUA_LUONG')),
 TrangThai VARCHAR2(12) DEFAULT 'DU_THAO' NOT NULL CHECK(TrangThai IN ('DU_THAO','DA_KY')),
 NguoiKy NVARCHAR2(100), NgayKy DATE,
 CHECK((TrangThai='DU_THAO' AND NguoiKy IS NULL AND NgayKy IS NULL) OR
       (TrangThai='DA_KY' AND NguoiKy IS NOT NULL AND NgayKy>=NgayLap))
);
CREATE TABLE DoiTuongQD (
 MaDT VARCHAR2(12) PRIMARY KEY, MaQD VARCHAR2(12) NOT NULL REFERENCES QuyetDinhKTKL(MaQD),
 MaNV VARCHAR2(12) REFERENCES NhanVien(MaNV), MaPB VARCHAR2(12) REFERENCES PhongBan(MaPB),
 SoTien NUMBER(15,2) NOT NULL CHECK(SoTien>0),
 CHECK((MaNV IS NOT NULL AND MaPB IS NULL) OR (MaNV IS NULL AND MaPB IS NOT NULL)),
 UNIQUE(MaQD,MaNV), UNIQUE(MaQD,MaPB)
);
CREATE TABLE BangLuong (
 MaBL VARCHAR2(12) PRIMARY KEY, Thang DATE NOT NULL UNIQUE, NgayLap DATE DEFAULT SYSDATE NOT NULL,
 CongChuan NUMBER(3) NOT NULL CHECK(CongChuan BETWEEN 1 AND 31),
 GioChuan NUMBER(2) DEFAULT 8 NOT NULL CHECK(GioChuan=8),
 CHECK(Thang=TRUNC(Thang,'MM'))
);
CREATE TABLE CTLuong (
 MaBL VARCHAR2(12) NOT NULL REFERENCES BangLuong(MaBL), MaNV VARCHAR2(12) NOT NULL REFERENCES NhanVien(MaNV),
 LuongCB NUMBER(15,2) NOT NULL, PhuCap NUMBER(15,2) NOT NULL,
 GioLam NUMBER(8,2) NOT NULL, GioPT NUMBER(8,2) NOT NULL,
 LuongCong NUMBER(15,2) NOT NULL, TienPT NUMBER(15,2) NOT NULL,
 TienThuong NUMBER(15,2) NOT NULL, TienPhat NUMBER(15,2) NOT NULL,
 BHXH NUMBER(15,2) NOT NULL, BHYT NUMBER(15,2) NOT NULL, ThucLinh NUMBER(15,2) NOT NULL,
 PRIMARY KEY(MaBL,MaNV), CHECK(GioLam>=0 AND GioPT>=0 AND BHXH>=0 AND BHYT>=0),
 CHECK(ThucLinh=LuongCong+TienPT+TienThuong-TienPhat-BHXH-BHYT)
);
CREATE TABLE PhanBoQD (
 MaPBQD VARCHAR2(12) PRIMARY KEY, MaDT VARCHAR2(12) NOT NULL REFERENCES DoiTuongQD(MaDT),
 MaNV VARCHAR2(12) NOT NULL REFERENCES NhanVien(MaNV), SoTien NUMBER(15,2) NOT NULL CHECK(SoTien>0),
 MaBL VARCHAR2(12), UNIQUE(MaDT,MaNV),
 FOREIGN KEY(MaBL,MaNV) REFERENCES CTLuong(MaBL,MaNV)
);
CREATE TABLE PhieuThuChi (
 MaPhieu VARCHAR2(12) PRIMARY KEY, MaPBQD VARCHAR2(12) NOT NULL UNIQUE REFERENCES PhanBoQD(MaPBQD),
 LoaiPhieu VARCHAR2(3) NOT NULL CHECK(LoaiPhieu IN ('THU','CHI')), NgayLap DATE DEFAULT SYSDATE NOT NULL,
 SoTien NUMBER(15,2) NOT NULL CHECK(SoTien>0), NguoiLap NVARCHAR2(100) NOT NULL
);
CREATE SEQUENCE SEQ_NS START WITH 100 INCREMENT BY 1;

