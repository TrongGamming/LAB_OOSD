CREATE OR REPLACE PROCEDURE sp_ThongKeTongHop(
    p_TuNgay IN DATE,
    p_DenNgay IN DATE
) AS
    v_TuNgay DATE := TRUNC(p_TuNgay);
    v_DenNgay DATE := TRUNC(p_DenNgay);
    v_Tmp DATE;
    v_Cursor SYS_REFCURSOR;
BEGIN
    IF v_TuNgay > v_DenNgay THEN
        v_Tmp := v_TuNgay;
        v_TuNgay := v_DenNgay;
        v_DenNgay := v_Tmp;
    END IF;

    -- 1. KPI
    OPEN v_Cursor FOR
      SELECT
        (SELECT COUNT(*)
         FROM PhieuMuon
         WHERE NgayMuon BETWEEN v_TuNgay AND v_DenNgay) AS LuotMuon,
        (SELECT COUNT(*) FROM vw_PhieuQuaHan) AS DangQuaHan,
        (SELECT COUNT(*)
         FROM LuotTai
         WHERE TRUNC(CAST(ThoiDiem AS DATE))
               BETWEEN v_TuNgay AND v_DenNgay) AS LuotTai,
        (SELECT COUNT(*)
         FROM YeuCauDatMua
         WHERE TRUNC(CAST(NgayGui AS DATE))
               BETWEEN v_TuNgay AND v_DenNgay) AS YeuCauDatMua,
        (SELECT COUNT(*)
         FROM EmailNhacHan
         WHERE TrangThai = 'DaGui'
           AND TRUNC(CAST(ThoiDiemGui AS DATE))
               BETWEEN v_TuNgay AND v_DenNgay) AS EmailDaGui
      FROM DUAL;

    DBMS_SQL.RETURN_RESULT(v_Cursor);

    -- 2. Lượt mượn theo chủ đề
    OPEN v_Cursor FOR
      SELECT
        cd.TenChuDe,
        COUNT(pm.Id) AS LuotMuon
      FROM ChuDe cd
      LEFT JOIN TaiLieu tl ON tl.MaChuDe = cd.MaChuDe
      LEFT JOIN BanSao bs ON bs.MaTaiLieu = tl.MaTaiLieu
      LEFT JOIN PhieuMuon pm
        ON pm.MaBanSao = bs.MaBanSao
       AND pm.NgayMuon BETWEEN v_TuNgay AND v_DenNgay
      GROUP BY cd.TenChuDe
      ORDER BY LuotMuon DESC;

    DBMS_SQL.RETURN_RESULT(v_Cursor);

    -- 3. Danh sách quá hạn
    OPEN v_Cursor FOR
      SELECT
        q.*,
        CASE
          WHEN e.TrangThai = 'DaGui' THEN N'Có'
          ELSE N'Không'
        END AS DaNhac
      FROM vw_PhieuQuaHan q
      LEFT JOIN EmailNhacHan e ON e.PhieuMuonId = q.Id
      ORDER BY q.SoNgayTre DESC;

    DBMS_SQL.RETURN_RESULT(v_Cursor);

    -- 4. Top 10 tài liệu được tải
    OPEN v_Cursor FOR
      SELECT *
      FROM (
        SELECT
          tl.MaTaiLieu,
          tl.TenTaiLieu,
          COUNT(*) AS LuotTai
        FROM LuotTai lt
        JOIN TaiLieu tl ON tl.MaTaiLieu = lt.MaTaiLieu
        WHERE TRUNC(CAST(lt.ThoiDiem AS DATE))
              BETWEEN v_TuNgay AND v_DenNgay
        GROUP BY tl.MaTaiLieu, tl.TenTaiLieu
        ORDER BY LuotTai DESC
      )
      FETCH FIRST 10 ROWS ONLY;

    DBMS_SQL.RETURN_RESULT(v_Cursor);

    -- 5. Đặt mua theo trạng thái
    OPEN v_Cursor FOR
      SELECT TrangThai, COUNT(*) AS SoYeuCau
      FROM YeuCauDatMua
      WHERE TRUNC(CAST(NgayGui AS DATE))
            BETWEEN v_TuNgay AND v_DenNgay
      GROUP BY TrangThai;

    DBMS_SQL.RETURN_RESULT(v_Cursor);
END;
/

