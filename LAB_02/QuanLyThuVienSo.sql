CREATE OR REPLACE PROCEDURE sp_DangKyMuon(
    p_MaThe IN VARCHAR2,
    p_MaTaiLieu IN VARCHAR2
) AS
    v_TinhTrangThe TheThuVien.TrangThai%TYPE;
    v_Han          TheThuVien.HanSuDung%TYPE;
    v_Count        NUMBER;
    v_MaBanSao     VARCHAR2(10);
    v_Id            NUMBER;
    v_Cursor        SYS_REFCURSOR;
BEGIN
    BEGIN
        SELECT TrangThai, HanSuDung
        INTO v_TinhTrangThe, v_Han
        FROM TheThuVien
        WHERE MaThe = p_MaThe;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20001, 'Mã thẻ không tồn tại.');
    END;

    IF v_TinhTrangThe <> 'HoatDong' THEN
        RAISE_APPLICATION_ERROR(
          -20002,
          'Thẻ đang bị khóa, báo mất hoặc đã hết hạn.'
        );
    END IF;

    IF v_Han < TRUNC(SYSDATE) THEN
        UPDATE TheThuVien
        SET TrangThai = 'HetHan'
        WHERE MaThe = p_MaThe;

        COMMIT;

        RAISE_APPLICATION_ERROR(
          -20003,
          'Thẻ thư viện đã hết hạn sử dụng.'
        );
    END IF;

    SELECT COUNT(*)
    INTO v_Count
    FROM TaiLieu
    WHERE MaTaiLieu = p_MaTaiLieu
      AND HinhThuc IN ('BanIn','CaHai');

    IF v_Count = 0 THEN
        RAISE_APPLICATION_ERROR(
          -20020,
          'Chỉ đăng ký mượn được tài liệu có bản in.'
        );
    END IF;

    SELECT COUNT(*)
    INTO v_Count
    FROM PhieuMuon
    WHERE MaThe = p_MaThe
      AND TrangThai = 'DangMuon'
      AND HanTra < TRUNC(SYSDATE);

    IF v_Count > 0 THEN
        RAISE_APPLICATION_ERROR(
          -20021,
          'Độc giả còn sách quá hạn chưa trả nên không được đăng ký thêm.'
        );
    END IF;

    SELECT
      (SELECT COUNT(*)
       FROM PhieuMuon
       WHERE MaThe = p_MaThe
         AND TrangThai = 'DangMuon')
      +
      (SELECT COUNT(*)
       FROM DangKyMuon
       WHERE MaThe = p_MaThe
         AND TrangThai = 'ChoNhan')
    INTO v_Count
    FROM DUAL;

    IF v_Count >= 5 THEN
        RAISE_APPLICATION_ERROR(
          -20022,
          'Đã đạt tối đa 5 cuốn (đang mượn + đang giữ chỗ).'
        );
    END IF;

    SELECT COUNT(*)
    INTO v_Count
    FROM DangKyMuon
    WHERE MaThe = p_MaThe
      AND MaTaiLieu = p_MaTaiLieu
      AND TrangThai = 'ChoNhan';

    IF v_Count > 0 THEN
        RAISE_APPLICATION_ERROR(
          -20023,
          'Bạn đã đăng ký tài liệu này và đang chờ nhận.'
        );
    END IF;

    SELECT MIN(MaBanSao)
    INTO v_MaBanSao
    FROM BanSao
    WHERE MaTaiLieu = p_MaTaiLieu
      AND TinhTrang = 'SanSang';

    IF v_MaBanSao IS NULL THEN
        RAISE_APPLICATION_ERROR(
          -20024,
          'Tài liệu đã hết bản sao sẵn sàng.'
        );
    END IF;

    SELECT MaBanSao
    INTO v_MaBanSao
    FROM BanSao
    WHERE MaBanSao = v_MaBanSao
    FOR UPDATE;

    UPDATE BanSao
    SET TinhTrang = 'DangGiu'
    WHERE MaBanSao = v_MaBanSao;

    INSERT INTO DangKyMuon(
      MaThe, MaTaiLieu, MaBanSaoGiu, HanNhan
    )
    VALUES(
      p_MaThe,
      p_MaTaiLieu,
      v_MaBanSao,
      TRUNC(SYSDATE) + 2
    )
    RETURNING Id INTO v_Id;

    COMMIT;

    OPEN v_Cursor FOR
      SELECT MaDangKy, MaBanSaoGiu, HanNhan
      FROM DangKyMuon
      WHERE Id = v_Id;

    DBMS_SQL.RETURN_RESULT(v_Cursor);
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(
          -20025,
          'Bản sao hoặc đăng ký vừa được giữ bởi giao dịch khác.'
        );
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/

CREATE OR REPLACE PROCEDURE sp_LapPhieuMuon(
    p_MaThe IN VARCHAR2,
    p_MaBanSao IN VARCHAR2,
    p_MaThuThu IN VARCHAR2,
    p_DangKyId IN NUMBER DEFAULT NULL
) AS
    v_TinhTrang VARCHAR2(10);
    v_Count NUMBER;
    v_Id NUMBER;
    v_Cursor SYS_REFCURSOR;
BEGIN
    BEGIN
        SELECT TinhTrang
        INTO v_TinhTrang
        FROM BanSao
        WHERE MaBanSao = p_MaBanSao
        FOR UPDATE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20030, 'Không tìm thấy bản sao.');
    END;

    IF p_DangKyId IS NOT NULL THEN
        UPDATE DangKyMuon
        SET TrangThai = 'DaNhan'
        WHERE Id = p_DangKyId
          AND MaThe = p_MaThe
          AND TrangThai = 'ChoNhan'
          AND MaBanSaoGiu = p_MaBanSao;

        IF SQL%ROWCOUNT = 0 THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(
              -20031,
              'Đăng ký không còn hiệu lực hoặc không khớp bản sao.'
            );
        END IF;
    ELSE
        IF v_TinhTrang <> 'SanSang' THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(
              -20032,
              'Bản sao không ở trạng thái sẵn sàng.'
            );
        END IF;

        SELECT COUNT(*)
        INTO v_Count
        FROM PhieuMuon
        WHERE MaThe = p_MaThe
          AND TrangThai = 'DangMuon'
          AND HanTra < TRUNC(SYSDATE);

        IF v_Count > 0 THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(
              -20021,
              'Độc giả còn sách quá hạn chưa trả.'
            );
        END IF;

        SELECT
          (SELECT COUNT(*)
           FROM PhieuMuon
           WHERE MaThe = p_MaThe
             AND TrangThai = 'DangMuon')
          +
          (SELECT COUNT(*)
           FROM DangKyMuon
           WHERE MaThe = p_MaThe
             AND TrangThai = 'ChoNhan')
        INTO v_Count
        FROM DUAL;

        IF v_Count >= 5 THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20022, 'Đã đạt tối đa 5 cuốn.');
        END IF;
    END IF;

    UPDATE BanSao
    SET TinhTrang = 'DangMuon'
    WHERE MaBanSao = p_MaBanSao;

    INSERT INTO PhieuMuon(
      MaThe,
      MaBanSao,
      DangKyId,
      MaThuThuLap,
      NgayMuon,
      HanTra
    )
    VALUES(
      p_MaThe,
      p_MaBanSao,
      p_DangKyId,
      p_MaThuThu,
      TRUNC(SYSDATE),
      TRUNC(SYSDATE) + 14
    )
    RETURNING Id INTO v_Id;

    COMMIT;

    OPEN v_Cursor FOR
      SELECT MaPhieuMuon, NgayMuon, HanTra
      FROM PhieuMuon
      WHERE Id = v_Id;

    DBMS_SQL.RETURN_RESULT(v_Cursor);
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/

CREATE OR REPLACE PROCEDURE sp_GhiNhanTraSach(
    p_MaBanSao IN VARCHAR2,
    p_MaThuThu IN VARCHAR2,
    p_TinhTrang IN VARCHAR2 DEFAULT 'NguyenVen',
    p_GhiChu IN NVARCHAR2 DEFAULT NULL
) AS
    v_Id NUMBER;
    v_HanTra DATE;
    v_MaThe VARCHAR2(12);
    v_Homnay DATE := TRUNC(SYSDATE);
    v_Cursor SYS_REFCURSOR;
BEGIN
    IF p_TinhTrang NOT IN ('NguyenVen','HuHong','Mat') THEN
        RAISE_APPLICATION_ERROR(
          -20040,
          'Tình trạng trả không hợp lệ.'
        );
    END IF;

    IF p_TinhTrang <> 'NguyenVen'
       AND TRIM(p_GhiChu) IS NULL THEN
        RAISE_APPLICATION_ERROR(
          -20041,
          'Phải nhập ghi chú khi sách hư hỏng hoặc mất.'
        );
    END IF;

    BEGIN
        SELECT Id, HanTra, MaThe
        INTO v_Id, v_HanTra, v_MaThe
        FROM PhieuMuon
        WHERE MaBanSao = p_MaBanSao
          AND TrangThai = 'DangMuon'
        FOR UPDATE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(
              -20042,
              'Bản sao không nằm trong danh sách đang cho mượn.'
            );
    END;

    UPDATE PhieuMuon
    SET NgayTra = v_Homnay,
        MaThuThuNhan = p_MaThuThu,
        GhiChu = p_GhiChu,
        SoNgayTre =
          CASE
            WHEN v_Homnay > v_HanTra
            THEN v_Homnay - v_HanTra
            ELSE 0
          END,
        TrangThai =
          CASE p_TinhTrang
            WHEN 'NguyenVen' THEN 'DaTra'
            WHEN 'HuHong' THEN 'TraHuHong'
            ELSE 'Mat'
          END
    WHERE Id = v_Id;

    UPDATE BanSao
    SET TinhTrang =
          CASE p_TinhTrang
            WHEN 'NguyenVen' THEN 'SanSang'
            WHEN 'HuHong' THEN 'CanKiemTra'
            ELSE 'Mat'
          END,
        GhiChu = NVL(p_GhiChu, GhiChu)
    WHERE MaBanSao = p_MaBanSao;

    COMMIT;

    OPEN v_Cursor FOR
      SELECT
        pm.MaPhieuMuon,
        pm.SoNgayTre,
        pm.TrangThai,
        (
          SELECT COUNT(*)
          FROM PhieuMuon x
          WHERE x.MaThe = pm.MaThe
            AND x.TrangThai = 'DangMuon'
        ) AS ConDangGiu
      FROM PhieuMuon pm
      WHERE pm.Id = v_Id;

    DBMS_SQL.RETURN_RESULT(v_Cursor);
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
