CREATE TABLE DocGia (
    MaDocGia      VARCHAR2(10)   NOT NULL,
    HoTen         NVARCHAR2(100) NOT NULL,
    LoaiDocGia    VARCHAR2(10)   NOT NULL,
    DonVi         NVARCHAR2(100),
    NgaySinh      DATE,
    Email         VARCHAR2(100)  NOT NULL,
    SoDienThoai   VARCHAR2(15),
    NgayTao       TIMESTAMP(0)   DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_DocGia PRIMARY KEY (MaDocGia),
    CONSTRAINT UQ_DocGia_Email UNIQUE (Email),
