CREATE OR REPLACE VIEW vw_TonKho AS
SELECT
    tl.MaTaiLieu,
    tl.TenTaiLieu,
    tl.HinhThuc,
    SUM(CASE WHEN bs.TinhTrang = 'SanSang' THEN 1 ELSE 0 END) AS SoLuongTon,
    SUM(CASE WHEN bs.TinhTrang = 'DangMuon' THEN 1 ELSE 0 END) AS DangMuon,
    SUM(CASE WHEN bs.TinhTrang = 'DangGiu' THEN 1 ELSE 0 END) AS DangGiu,
    COUNT(bs.MaBanSao) AS TongBanSao
FROM TaiLieu tl
LEFT JOIN BanSao bs ON bs.MaTaiLieu = tl.MaTaiLieu
GROUP BY tl.MaTaiLieu, tl.TenTaiLieu, tl.HinhThuc;

CREATE OR REPLACE VIEW vw_PhieuQuaHan AS
SELECT
    pm.Id,
    pm.MaPhieuMuon,
    pm.MaThe,
    dg.MaDocGia,
    dg.HoTen,
    dg.Email,
    bs.MaBanSao,
    tl.MaTaiLieu,
    tl.TenTaiLieu,
    pm.NgayMuon,
    pm.HanTra,
    TRUNC(SYSDATE) - pm.HanTra AS SoNgayTre
FROM PhieuMuon pm
JOIN TheThuVien t ON t.MaThe = pm.MaThe
JOIN DocGia dg ON dg.MaDocGia = t.MaDocGia
JOIN BanSao bs ON bs.MaBanSao = pm.MaBanSao
JOIN TaiLieu tl ON tl.MaTaiLieu = bs.MaTaiLieu
WHERE pm.TrangThai = 'DangMuon'
  AND pm.HanTra < TRUNC(SYSDATE);

CREATE OR REPLACE VIEW vw_TinhTrangMuon AS
SELECT
    tl.MaTaiLieu,
    tl.TenTaiLieu,
    bs.MaBanSao,
    pm.MaPhieuMuon,
    dg.HoTen AS DocGia,
    pm.NgayMuon,
    pm.HanTra,
    CASE WHEN pm.HanTra < TRUNC(SYSDATE) THEN 1 ELSE 0 END AS QuaHan,
    CASE WHEN pm.HanTra < TRUNC(SYSDATE)
         THEN TRUNC(SYSDATE) - pm.HanTra
         ELSE 0
    END AS SoNgayTre
FROM PhieuMuon pm
JOIN BanSao bs ON bs.MaBanSao = pm.MaBanSao
JOIN TaiLieu tl ON tl.MaTaiLieu = bs.MaTaiLieu
JOIN TheThuVien t ON t.MaThe = pm.MaThe
JOIN DocGia dg ON dg.MaDocGia = t.MaDocGia
WHERE pm.TrangThai = 'DangMuon';

-- =====================================================================
-- 5. STORED PROCEDURE
-- Oracle dùng DBMS_SQL.RETURN_RESULT + SYS_REFCURSOR
-- để trả result set về ứng dụng.
-- =====================================================================

CREATE OR REPLACE PROCEDURE sp_XacThucMaThe(
    p_MaThe IN VARCHAR2
) AS
    v_TrangThai TheThuVien.TrangThai%TYPE;
    v_Han       TheThuVien.HanSuDung%TYPE;
    v_Cursor    SYS_REFCURSOR;
BEGIN
    BEGIN
        SELECT TrangThai, HanSuDung
        INTO v_TrangThai, v_Han
        FROM TheThuVien
        WHERE MaThe = p_MaThe;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20001, 'Mã thẻ không tồn tại.');
    END;

    IF v_TrangThai <> 'HoatDong' THEN
        RAISE_APPLICATION_ERROR(
          -20002,
          'Thẻ đang bị khóa, báo mất hoặc đã hết hạn.'
        );
    END IF;

    IF v_Han < TRUNC(SYSDATE) THEN
        UPDATE TheThuVien
        SET TrangThai = 'HetHan'
        WHERE MaThe = p_MaThe;

        COMMIT;

        RAISE_APPLICATION_ERROR(
          -20003,
          'Thẻ thư viện đã hết hạn sử dụng.'
        );
    END IF;

    OPEN v_Cursor FOR
      SELECT
          t.MaThe,
          t.HanSuDung,
          dg.MaDocGia,
          dg.HoTen,
          dg.LoaiDocGia,
          dg.Email
      FROM TheThuVien t
      JOIN DocGia dg ON dg.MaDocGia = t.MaDocGia
      WHERE t.MaThe = p_MaThe;

    DBMS_SQL.RETURN_RESULT(v_Cursor);
END;
