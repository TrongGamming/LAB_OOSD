CREATE TABLE TheThuVien (
    MaThe        VARCHAR2(12) NOT NULL,
    MaDocGia     VARCHAR2(10) NOT NULL,
    NgayCap      DATE NOT NULL,
    HanSuDung    DATE NOT NULL,
    TrangThai    VARCHAR2(10) DEFAULT 'HoatDong' NOT NULL,
    CONSTRAINT PK_TheThuVien PRIMARY KEY (MaThe),
    CONSTRAINT FK_The_DocGia
      FOREIGN KEY (MaDocGia) REFERENCES DocGia(MaDocGia),
    CONSTRAINT CK_The_TrangThai
      CHECK (TrangThai IN ('HoatDong','HetHan','Khoa','Mat')),
    CONSTRAINT CK_The_Han CHECK (HanSuDung > NgayCap)
);

